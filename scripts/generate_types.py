"""Gera src/amebas/types.py (TypedDicts) a partir de protocol/bot-protocol.schema.json.

Rode da raiz do pacote: `uv run --group dev python scripts/generate_types.py`.
No repo público o schema vem do Amebas-Arena/protocol; no monorepo, `scripts/sync_schema.py` copia do pacote do protocolo.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
out = root / "src" / "amebas" / "types.py"

subprocess.run(
    [
        sys.executable, "-m", "datamodel_code_generator",
        "--input", str(root / "protocol" / "bot-protocol.schema.json"),
        "--input-file-type", "jsonschema",
        "--output-model-type", "typing.TypedDict",
        "--target-python-version", "3.10",
        "--use-schema-description", "--use-field-description",
        "--use-union-operator", "--use-standard-collections",
        "--disable-timestamp",
        "--output", str(out),
    ],
    check=True,
)
text = out.read_text(encoding="utf-8")
# o closed=True (PEP 728) pede um typing_extensions muito novo e não muda nada em tempo de execução
text = text.replace(", closed=True", "")
text = text.replace("from typing_extensions import NotRequired, TypedDict", "from typing_extensions import NotRequired, TypedDict  # noqa: F401")
header = "# Gerado de protocol/bot-protocol.schema.json por scripts/generate_types.py. Não edite à mão: o schema é a fonte.\n"
text = re.sub(r"^# generated by datamodel-codegen:\n#   filename:.*\n", header, text, count=1)
out.write_text(text, encoding="utf-8")
print(f"gravado: {out}")

# --- os decoradores tipados por evento (@bot.on_chat_message...), um por evento do schema ---
import json

schema = json.loads((root / "protocol" / "bot-protocol.schema.json").read_text(encoding="utf-8"))
defs = schema["$defs"]
events = {}
for variant in defs["RoomEvent"]["oneOf"]:
    name = variant["$ref"].rsplit("/", 1)[1]
    events[defs[name]["properties"]["type"]["const"]] = name
lines = [
    "# Gerado de protocol/bot-protocol.schema.json por scripts/generate_types.py. Não edite à mão.",
    "",
    "from __future__ import annotations",
    "",
    "from typing import Any, Awaitable, Callable, TypeVar, Union",
    "",
    "from .types import (",
    "    ReadyMessage,",
    *[f"    {name}," for name in sorted(events.values())],
    ")",
    "",
    "H = TypeVar('H', bound=Callable[..., Any])",
    "",
    "",
    "class EventDecorators:",
    '    """Um decorador por evento da sala, com o tipo do evento no argumento do handler."""',
    "",
    "    def on(self, event: str, handler: H | None = None) -> Any:  # implementado no RoomBot",
    "        raise NotImplementedError",
    "",
]
lines += [
    "    def on_ready(self, handler: Callable[[ReadyMessage], Union[None, Awaitable[None]]]) -> Callable[[ReadyMessage], Union[None, Awaitable[None]]]:",
    '        """Escuta o ready: a auth foi aceita (a cada conexão, inclusive depois de reconectar)."""',
    "        return self.on('ready', handler)",
    "",
]
for event, typ in events.items():
    method = "on_" + event.replace(".", "_")
    lines += [
        f"    def {method}(self, handler: Callable[[{typ}], Union[None, Awaitable[None]]]) -> Callable[[{typ}], Union[None, Awaitable[None]]]:",
        f'        """Escuta o evento {event!r}; serve de decorador."""',
        f"        return self.on({event!r}, handler)",
        "",
    ]
(root / "src" / "amebas" / "_events.py").write_text("\n".join(lines), encoding="utf-8")
print("gravado: src/amebas/_events.py")
